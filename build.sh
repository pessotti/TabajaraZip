#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")"
app="TabajaraZip.app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp Packaging/Info.plist "$app/Contents/Info.plist"
ditto Resources "$app/Contents/Resources"
cp LEIA-ME.md "$app/Contents/Resources/Guia.md"
cp LICENSE "$app/Contents/Resources/TabajaraZip-LICENSE.txt"
cp THIRD-PARTY.md "$app/Contents/Resources/THIRD-PARTY.md"
python3 Scripts/build_icon.py
build_dir="${TMPDIR:-/tmp}/tabajara-build"
mkdir -p "$app/Contents/MacOS" "$build_dir"
printf '["AppIntent","AppEntity","AppEnum","AppShortcutsProvider","EntityQuery","DynamicOptionsProvider"]' > "$build_dir/protocols.json"
swiftc -target arm64-apple-macosx14.0 -parse-as-library -whole-module-optimization -module-name TabajaraZIP -emit-const-values -emit-const-values-path "$build_dir/values.swiftconstvalues" -Xfrontend -const-gather-protocols-file -Xfrontend "$build_dir/protocols.json" Sources/*.swift -o "$app/Contents/MacOS/TabajaraZip" -framework SwiftUI -framework AppKit -framework QuickLookUI -framework PDFKit -framework AppIntents -module-cache-path "${TMPDIR:-/tmp}/zipdesk-module-cache"
for source in "$PWD"/Sources/*.swift; do printf '%s\n' "$source"; done > "$build_dir/sources.list"
printf '%s\n' "$build_dir/values.swiftconstvalues" > "$build_dir/const.list"
xcrun appintentsmetadataprocessor --output "$PWD/$app/Contents/Resources" --toolchain-dir "$(xcode-select -p)/Toolchains/XcodeDefault.xctoolchain" --module-name TabajaraZIP --sdk-root "$(xcrun --show-sdk-path)" --xcode-version "$(xcodebuild -version | awk '/Build version/{print $3}')" --platform-family macOS --deployment-target 14.0 --target-triple arm64-apple-macosx14.0 --source-file-list "$build_dir/sources.list" --swift-const-vals-list "$build_dir/const.list"
preview="$app/Contents/PlugIns/TabajaraPreview.appex"
mkdir -p "$preview/Contents/MacOS"
cp Extensions/QuickLook/Info.plist "$preview/Contents/Info.plist"
swiftc -target arm64-apple-macosx14.0 -parse-as-library -emit-executable -module-name TabajaraPreview -application-extension -Xlinker -e -Xlinker _NSExtensionMain Sources/ArchiveEngine.swift Extensions/QuickLook/PreviewViewController.swift -o "$preview/Contents/MacOS/TabajaraPreview" -framework Cocoa -framework Quartz -module-cache-path "${TMPDIR:-/tmp}/zipdesk-module-cache"
codesign --force --sign - --entitlements Extensions/QuickLook/Entitlements.plist "$preview"
codesign --force --sign - "$app/Contents/Resources/Tools/7zz"
codesign --force --sign - "$app"
codesign --verify --deep --strict "$app"
